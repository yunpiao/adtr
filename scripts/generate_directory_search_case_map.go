//go:build ignore

// Regenerate with the repository-pinned Go toolchain from the repository root.
// This is data from Go's Unicode tables, not JavaScript/locale case folding.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"os"
	"runtime"
	"unicode"
	"unicode/utf8"
)

func main() {
	check := flag.Bool("check", false, "verify the checked-in generated table")
	flag.Parse()
	if runtime.Version() != "go1.27.1" || unicode.Version != "17.0.0" {
		panic("directory search generator requires repository-pinned Go 1.27.1 / Unicode 17.0.0; review upgrades explicitly")
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Generated by scripts/generate_directory_search_case_map.go; do not edit.")
	fmt.Fprintln(&out, "// Go Unicode simple lowercase: no normalization, locale or expansions.")
	fmt.Fprintf(&out, "export const directorySearchUnicodeVersion = %q;\n", unicode.Version)
	// Independent oracle covers every Unicode scalar in ascending order, encoded
	// after unicode.ToLower. Surrogates are not Unicode scalar values.
	hash := sha256.New()
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if utf8.ValidRune(r) {
			fmt.Fprint(hash, string(unicode.ToLower(r)))
		}
	}
	fmt.Fprintf(&out, "export const directorySearchScalarLowerSHA256 =\n  %q;\n", fmt.Sprintf("%x", hash.Sum(nil)))
	fmt.Fprintln(&out, "export const directorySearchLowerRanges = [")
	for _, row := range unicode.CaseRanges {
		if delta := row.Delta[unicode.LowerCase]; delta != 0 {
			fmt.Fprintf(&out, "  [%d, %d, %d],\n", row.Lo, row.Hi, delta)
		}
	}
	fmt.Fprintln(&out, "] as const;")
	path := "web/src/directory-search-case-map.ts"
	if *check {
		actual, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(actual, out.Bytes()) {
			panic("directory search case map differs from pinned Go; regenerate and review")
		}
	} else if err := os.WriteFile(path, out.Bytes(), 0644); err != nil {
		panic(err)
	}
}
